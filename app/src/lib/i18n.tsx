// English is inline at every call site, so this dictionary only exists to type the locale table.
const en: Dict = {}

const DICTS: Record<Locale, Dict> = { zh, en }

/**
 * The same lookup for code that runs outside React — a route's `head()` — where no hook is
 * available. It reads the locale the same way the provider does on first mount.
 */
export const translate = (key: string, fallback: string) => DICTS[detectLocale()][key] ?? fallback

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (key: string, fallback: string) => string }
const I18nContext = createContext<Ctx>({ locale: 'en', setLocale: () => {}, t: (_k, f) => f })

export function I18nProvider({ children, initial }: { children: React.ReactNode; initial?: Locale }) {
  // `initial` is read from the cookie on the server, so the first paint is already in the right
  // language and hydration agrees with it. Without one (no cookie yet) render English and correct
  // after mount from the browser's preference. That still flashes for a Chinese browser, but only
  // ever once — picking a language writes the cookie, and every later request is server-rendered
  // correctly.
  const [locale, setLocaleState] = useState<Locale>(initial ?? 'en')
  useEffect(() => { if (!initial) setLocaleState(detectLocale()) }, [initial])

  const setLocale = (l: Locale) => {
    setLocaleState(l)
    try { localStorage.setItem(STORAGE_KEY, l) } catch { /* private mode */ }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en'
      // A year, so a returning visitor is server-rendered in their language. Lax is enough: this
      // is a display preference, not anything that needs to survive a cross-site POST.
      document.cookie = `${LOCALE_COOKIE}=${l}; path=/; max-age=31536000; samesite=lax`
    }
  }

  /** `fallback` is the English source text, so an untranslated key still reads correctly. */
  const t = (key: string, fallback: string) => DICTS[locale][key] ?? fallback

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
/** `t('nav.pricing', 'Pricing')` — the second argument is the English original. */
export const useT = () => useI18n().t
