export type Word = keyof typeof words
export const translate = (locale: Locale, key: string) => words[key as Word]?.[locale === 'zh' ? 0 : 1] ?? key
/** Database and API errors arrive as sentences; find the code the triggers and checks raise. */
export function errorKey(message: string) {
  if (message in words) return message
  if (/duplicate key.*key/i.test(message)) return 'duplicate_key'
  if (/permission denied|read.only/i.test(message)) return 'read_only'
  const known = ['project_archived', 'task_identity_locked', 'quota_exceeded'].find((code) => message.includes(code))
  return known && known in words ? known : 'generic_error'
}
