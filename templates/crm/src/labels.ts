/** Database and API messages arrive as text; known rule names map to a sentence. */
export function errorKey(message: string) {
  if (message in words) return message
  if (message.includes('crm_contact_company')) return 'crm_contact_company'
  if (/violates|invalid input/i.test(message)) return 'rejected'
  return message || 'generic_error'
}
